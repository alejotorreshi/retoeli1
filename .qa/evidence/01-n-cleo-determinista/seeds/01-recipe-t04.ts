import { readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { call, proyectar } from "./qa-lib.ts";
const caso = "ec-corp-andina";
const ls = async () => existsSync(`out/${caso}`) ? (await readdir(`out/${caso}`, { recursive: true })).sort() : [];
const show = (l: string, r: any) => console.log(l, JSON.stringify(r));
show("A confirmado=false:", await call("simular_envio", { caso, confirmado: false })); console.log("  files:", await ls());
show("B confirmado missing:", await call("simular_envio", { caso })); console.log("  files:", await ls());
show("C confirmado='true':", await call("simular_envio", { caso, confirmado: "true" }));
show("D confirmado=true, no paquete:", await call("simular_envio", { caso, confirmado: true })); console.log("  files:", await ls());
await call("leer_solicitud", { caso });
const m = await call("mapear_campos", { caso, campos: [] });
const g = await call("generar_formulario", { caso, mapeo: proyectar(m) });
const p = await call("armar_paquete", { caso });
console.log("armar_paquete listo_para_firma:", p.data?.listo_para_firma, "bloqueos:", JSON.stringify(p.data?.bloqueos));
const before = await ls();
show("E confirmado=true with paquete:", await call("simular_envio", { caso, confirmado: true }));
const after = await ls();
console.log("  new files:", after.filter((f) => !before.includes(f)));
